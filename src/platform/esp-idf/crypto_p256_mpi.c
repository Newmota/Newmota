/** @file
 * @brief Compact BearSSL P-256 provider for ESP chips with an MPI (RSA) engine.
 * Every field multiplication runs on the MPI engine through the ROM bigint driver; the
 * point arithmetic around it is constant time: complete projective addition for a = -3
 * (Renes, Costello and Batina 2016, algorithm 4, also used for doubling), a fixed
 * 256-step Montgomery ladder with masked swaps, and a masked 4-tooth comb for the generator. Points
 * must lie on the curve, scalars must be in [1, n - 1], and an infinite result is rejected. The SDK
 * MPI lock and clock owner surround each operation; the ROM enable and disable calls are never
 * used, because the SDK owns the clock, reset and power state.
 */
#include "crypto_p256_glue.h"
#include "esp_crypto_lock.h"
#include "esp_crypto_periph_clk.h"
#include "hal/mpi_hal.h"
#include "rom/bigint.h"
#include "sdkconfig.h"
#include "soc/soc_caps.h"
#if CONFIG_IDF_TARGET_ESP32
#include "dport_access.h"
#endif

#if !SOC_MPI_SUPPORTED
#error "ROM P-256 requires the MPI engine"
#endif

#define WORDS 8

/** @brief Field element: little-endian 32-bit limbs, fully reduced modulo p. */
typedef uint32_t fe[WORDS];

/** @brief Projective point (X:Y:Z); infinity is (0:1:0). */
typedef struct {
    fe x, y, z;
} point;

