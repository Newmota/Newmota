#if CONFIG_IDF_TARGET_ESP32
/* The ESP32 engine works on 512-bit operands: Montgomery product x*y*2^-512, then a second
   product with 2^1024 mod p returns x*y mod p. */
static const uint32_t P512[16] = {
    0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, 0x00000000, 0x00000000, 0x00000000, 0x00000001, 0xFFFFFFFF};
static const uint32_t R1024[16] = {
    0x00000015, 0xFFFFFFD9, 0xFFFFFFC6, 0xFFFFFFBC, 0x00000011, 0x00000040, 0x00000032, 0x00000069};
#else
/* ets_bigint_modmult computes x*y*rb*2^-512 mod m; rb = 2^512 mod p gives x*y mod p. */
static const fe RR = {
    0x00000003, 0x00000000, 0xFFFFFFFF, 0xFFFFFFFB, 0xFFFFFFFE, 0xFFFFFFFF, 0xFFFFFFFD, 0x00000004};
#endif

/** @brief Store hi:a - p if hi:a >= p, else hi:a; requires hi:a < 2p. */
static void fe_reduce(uint32_t* d, const uint32_t* a, uint32_t hi) {
    uint32_t t[WORDS], borrow = 0;
    for (size_t i = 0; i < WORDS; ++i) {
        uint64_t v = (uint64_t)a[i] - P[i] - borrow;
        t[i] = (uint32_t)v;
        borrow = (uint32_t)(v >> 63);
    }
    uint32_t mask = -((hi & 1) | (borrow ^ 1));
    for (size_t i = 0; i < WORDS; ++i)
        d[i] = a[i] ^ ((a[i] ^ t[i]) & mask);
}

static void fe_add(fe d, const fe a, const fe b) {
    uint32_t s[WORDS], carry = 0;
    for (size_t i = 0; i < WORDS; ++i) {
        uint64_t v = (uint64_t)a[i] + b[i] + carry;
        s[i] = (uint32_t)v;
        carry = (uint32_t)(v >> 32);
    }
    fe_reduce(d, s, carry);
}

static void fe_sub(fe d, const fe a, const fe b) {
    uint32_t s[WORDS], borrow = 0, carry = 0;
    for (size_t i = 0; i < WORDS; ++i) {
        uint64_t v = (uint64_t)a[i] - b[i] - borrow;
        s[i] = (uint32_t)v;
        borrow = (uint32_t)(v >> 63);
    }
    uint32_t mask = -borrow;
    for (size_t i = 0; i < WORDS; ++i) {
        uint64_t v = (uint64_t)s[i] + (P[i] & mask) + carry;
        d[i] = (uint32_t)v;
        carry = (uint32_t)(v >> 32);
    }
}

/** @brief Field product on the MPI engine. Caller holds the SDK MPI lock. */
static void fe_mul(fe d, const fe a, const fe b) {
#if CONFIG_IDF_TARGET_ESP32
    uint32_t x[16] = {0}, y[16] = {0}, z[16];
    memcpy(x, a, sizeof(fe));
    memcpy(y, b, sizeof(fe));
    DPORT_STALL_OTHER_CPU_START();
    ets_bigint_montgomery_mult_prepare(x, y, (uint32_t*)P512, 1, 512, false);
    ets_bigint_wait_finish();
    ets_bigint_montgomery_mult_getz(z, 512);
    ets_bigint_montgomery_mult_prepare(z, (uint32_t*)R1024, (uint32_t*)P512, 1, 512, true);
    ets_bigint_wait_finish();
    ets_bigint_montgomery_mult_getz(z, 512);
    DPORT_STALL_OTHER_CPU_END();
    fe_reduce(d, z, z[WORDS]);
    nm_crypto_zero(x, sizeof x);
    nm_crypto_zero(y, sizeof y);
#else
    uint32_t z[WORDS];
    ets_bigint_modmult(a, b, P, 1, RR, WORDS);
    ets_bigint_wait_finish();
    ets_bigint_getz(z, WORDS);
    fe_reduce(d, z, 0);
#endif
    nm_crypto_zero(z, sizeof z);
}

/** @brief Inverse by Fermat's little theorem; the exponent p - 2 is public. Zero maps to zero. */
static void fe_inv(fe d, const fe a) {
    fe r = {1};
    for (int i = 255; i >= 0; --i) {
        fe_mul(r, r, r);
        uint32_t e = i < 32 ? 0xFFFFFFFD : P[i >> 5];
        if ((e >> (i & 31)) & 1)
            fe_mul(r, r, a);
    }
    memcpy(d, r, sizeof r);
    nm_crypto_zero(r, sizeof r);
}

static uint32_t fe_is_zero(const fe a) {
    uint32_t acc = 0;
    for (size_t i = 0; i < WORDS; ++i)
        acc |= a[i];
    return (uint32_t)(((uint64_t)acc - 1) >> 63);
}

static void fe_decode(fe d, const unsigned char* src) {
    for (size_t i = 0; i < WORDS; ++i)
        d[i] = br_dec32be(src + 4 * (WORDS - 1 - i));
}

static void fe_encode(unsigned char* dst, const fe a) {
    for (size_t i = 0; i < WORDS; ++i)
        br_enc32be(dst + 4 * (WORDS - 1 - i), a[i]);
}

/** @brief Complete addition r = p + q for any inputs, including equal points and infinity. */
static void point_add(point* r, const point* p, const point* q) {
    fe t0, t1, t2, t3, t4, x3, y3, z3;
    fe_mul(t0, p->x, q->x);
    fe_mul(t1, p->y, q->y);
    fe_mul(t2, p->z, q->z);
    fe_add(t3, p->x, p->y);
    fe_add(t4, q->x, q->y);
    fe_mul(t3, t3, t4);
    fe_add(t4, t0, t1);
    fe_sub(t3, t3, t4);
    fe_add(t4, p->y, p->z);
    fe_add(x3, q->y, q->z);
    fe_mul(t4, t4, x3);
    fe_add(x3, t1, t2);
    fe_sub(t4, t4, x3);
    fe_add(x3, p->x, p->z);
    fe_add(y3, q->x, q->z);
    fe_mul(x3, x3, y3);
    fe_add(y3, t0, t2);
    fe_sub(y3, x3, y3);
    fe_mul(z3, B, t2);
    fe_sub(x3, y3, z3);
    fe_add(z3, x3, x3);
    fe_add(x3, x3, z3);
    fe_sub(z3, t1, x3);
    fe_add(x3, t1, x3);
    fe_mul(y3, B, y3);
    fe_add(t1, t2, t2);
    fe_add(t2, t1, t2);
    fe_sub(y3, y3, t2);
    fe_sub(y3, y3, t0);
    fe_add(t1, y3, y3);
    fe_add(y3, t1, y3);
    fe_add(t1, t0, t0);
    fe_add(t0, t1, t0);
    fe_sub(t0, t0, t2);
    fe_mul(t1, t4, y3);
    fe_mul(t2, t0, y3);
    fe_mul(y3, x3, z3);
    fe_add(y3, y3, t2);
    fe_mul(x3, x3, t3);
    fe_sub(x3, x3, t1);
    fe_mul(z3, t4, z3);
    fe_mul(t1, t3, t0);
    fe_add(z3, z3, t1);
    memcpy(r->x, x3, sizeof x3);
    memcpy(r->y, y3, sizeof y3);
    memcpy(r->z, z3, sizeof z3);
    nm_crypto_zero(t0, sizeof t0);
    nm_crypto_zero(t1, sizeof t1);
    nm_crypto_zero(t2, sizeof t2);
    nm_crypto_zero(t3, sizeof t3);
    nm_crypto_zero(t4, sizeof t4);
}

static void point_swap(point* a, point* b, uint32_t bit) {
    uint32_t mask = -bit, *u = (uint32_t*)a, *v = (uint32_t*)b;
    for (size_t i = 0; i < sizeof(point) / sizeof(uint32_t); ++i) {
        uint32_t t = (u[i] ^ v[i]) & mask;
        u[i] ^= t;
        v[i] ^= t;
    }
}

/** @brief r = k * p over all 256 bits of the big-endian scalar, in constant time. */
static void ladder(point* r, const point* p, const unsigned char* k) {
    point r0 = {{0}, {1}, {0}}, r1 = *p;
    for (size_t i = 0; i < 256; ++i) {
        uint32_t bit = (k[i >> 3] >> (7 - (i & 7))) & 1;
        point_swap(&r0, &r1, bit);
        point_add(&r1, &r0, &r1);
        point_add(&r0, &r0, &r0);
        point_swap(&r0, &r1, bit);
    }
    *r = r0;
    nm_crypto_zero(&r0, sizeof r0);
    nm_crypto_zero(&r1, sizeof r1);
}

/**
 * @brief r = k * G with a 4-tooth comb: 64 doublings and 64 additions instead of the ladder's
 * 256 each. Every step reads the whole table with masks, so the access pattern is fixed.
 */
static void comb_generator(point* r, const unsigned char* k) {
    point acc = {{0}, {1}, {0}}, t;
    for (int col = 63; col >= 0; --col) {
        uint32_t idx = 0;
        for (unsigned tooth = 0; tooth < 4; ++tooth) {
            unsigned bit = (unsigned)col + 64 * tooth;
            idx |= (uint32_t)((k[31 - (bit >> 3)] >> (bit & 7)) & 1) << tooth;
        }
        point_add(&acc, &acc, &acc);
        memset(&t, 0, sizeof t);
        t.y[0] = 1;
        for (uint32_t j = 1; j < 16; ++j) {
            uint32_t hit = (uint32_t)(((uint64_t)(j ^ idx) - 1) >> 63), mask = -hit;
            for (size_t i = 0; i < WORDS; ++i) {
                t.x[i] |= COMB[j - 1].x[i] & mask;
                t.y[i] = (t.y[i] & ~mask) | (COMB[j - 1].y[i] & mask);
            }
            t.z[0] |= hit;
        }
        point_add(&acc, &acc, &t);
    }
    *r = acc;
    nm_crypto_zero(&acc, sizeof acc);
    nm_crypto_zero(&t, sizeof t);
}

/** @brief k * p; the comb serves the generator, which is public, so the branch leaks nothing. */
static void scalar_mul(
    point* r, const point* p, const unsigned char* encoded, const unsigned char* k) {
    if (memcmp(encoded, br_secp256r1.generator, 65) == 0)
        comb_generator(r, k);
    else
        ladder(r, p, k);
}

static void decode_point(point* p, const unsigned char* src) {
    fe_decode(p->x, src + 1);
    fe_decode(p->y, src + 33);
    memcpy(p->z, ONE, sizeof ONE);
}

/** @brief Check y^2 = x^3 - 3x + b for an affine point. Caller holds the MPI lock. */
static uint32_t on_curve(const point* p) {
    fe l, r, t;
    fe_mul(l, p->y, p->y);
    fe_mul(r, p->x, p->x);
    fe_mul(r, r, p->x);
    fe_add(t, p->x, p->x);
    fe_add(t, t, p->x);
    fe_sub(r, r, t);
    fe_add(r, r, B);
    fe_sub(l, l, r);
    return fe_is_zero(l);
}

/** @brief Hold the SDK MPI owner for one complete operation. */
static void mpi_begin(void) {
    esp_crypto_mpi_lock_acquire();
    esp_crypto_mpi_enable_periph_clk(true);
    mpi_hal_enable_hardware_hw_op();
}

/** @brief Overwrite the engine operands, then return the engine to the SDK. */
static void mpi_end(void) {
    fe zero = {0};
    fe_mul(zero, zero, zero);
    mpi_hal_disable_hardware_hw_op();
    esp_crypto_mpi_enable_periph_clk(false);
    esp_crypto_mpi_lock_release();
}

static uint32_t calculate(unsigned char* a, const unsigned char* b, size_t len,
    const unsigned char* x, size_t xlen, const unsigned char* y, size_t ylen, int sum) {
    point p, q, r;
    unsigned char k[32], l[32];
    fe zi;
    uint32_t valid;
    if (len != 65)
        return 0;
    const unsigned char* qb = b ? b : br_secp256r1.generator;
    valid = p256_canonical_point(a) & p256_decode_scalar(k, x, xlen, sum);
    if (sum)
        valid &= p256_canonical_point(qb) & p256_decode_scalar(l, y, ylen, 1);
    if (valid) {
        decode_point(&p, a);
        if (sum)
            decode_point(&q, qb);
        mpi_begin();
        valid = on_curve(&p) & (!sum || on_curve(&q));
        if (valid) {
            scalar_mul(&r, &p, a, k);
            if (sum) {
                scalar_mul(&q, &q, qb, l);
                point_add(&r, &r, &q);
            }
            valid = !fe_is_zero(r.z);
            fe_inv(zi, r.z);
            fe_mul(r.x, r.x, zi);
            fe_mul(r.y, r.y, zi);
        }
        mpi_end();
        if (valid) {
            a[0] = 4;
            fe_encode(a + 1, r.x);
            fe_encode(a + 33, r.y);
        }
    }
    nm_crypto_zero(&p, sizeof p);
    nm_crypto_zero(&q, sizeof q);
    nm_crypto_zero(&r, sizeof r);
    nm_crypto_zero(k, sizeof k);
    nm_crypto_zero(l, sizeof l);
    nm_crypto_zero(zi, sizeof zi);
    return valid;
}
